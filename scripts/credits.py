#!/usr/bin/env python3
"""Generate a credits.md from the music and SFX libraries, and optionally one or more footage
source manifests (a tests/<name>/sources.json), so a render's attribution text is never
hand-typed from scratch and never silently skips an uncleared sample.

  scripts/credits.py --music ../music/index.json --sfx ../sfx/index.json --out credits.md
  scripts/credits.py --music ../music/index.json --sfx ../sfx/index.json \\
      --footage tests/fontainebleau/sources.json --out tests/fontainebleau/credits.md \\
      --tracks "Court of the Queen" --effects outro-hit

With no --tracks/--effects/--footage-files filter, every entry in the given index (every cleared
sfx entry, every footage file) is listed, which is the right default for a library-wide reference
credits.md. An uncleared sfx entry (sfx_library.is_cleared is False, e.g. the 13 reel clips before
they carry a recorded licence and credit) is listed separately under "Not cleared, do not
publish", never folded in with the publishable credit lines.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'engine'))
import sfx_library as lib


def _load(path):
    if not path:
        return None
    return json.load(open(path, encoding='utf-8'))


def music_section(index, only=None):
    lines = ['## Music', '']
    tracks = index or []
    if only:
        tracks = [t for t in tracks if t.get('path') in only or t.get('title') in only]
    if not tracks:
        return lines + ['(none)', '']
    for t in tracks:
        lines.append(f"- **{t.get('title', t.get('path'))}**")
        credit = t.get('credit') or '(no credit string recorded, do not publish)'
        lines.append('  ```')
        lines += [f'  {line}' for line in credit.splitlines()]
        lines.append('  ```')
        lines.append('')
    return lines


def sfx_section(index, only=None):
    effects = (index or {}).get('effects', [])
    if only:
        effects = [e for e in effects if e.get('id') in only or e.get('name') in only]
    cleared = [e for e in effects if lib.is_cleared(e)]
    uncleared = [e for e in effects if not lib.is_cleared(e)]
    lines = ['## Sound effects', '']
    if cleared:
        for e in cleared:
            lines.append(f"- **{e['name']}** ({e['id']}): {e['credit']}")
        lines.append('')
    else:
        lines += ['(none cleared yet)', '']
    if uncleared:
        lines.append('### Not cleared, do not publish')
        lines.append('')
        for e in uncleared:
            lines.append(f"- **{e['name']}** ({e['id']}): {e.get('licence', 'unknown')}")
        lines.append('')
    return lines


def footage_section(manifests, only=None):
    files = []
    for manifest in manifests:
        for f in (manifest or {}).get('files', []):
            if only and f.get('local_path') not in only and f.get('title') not in only:
                continue
            files.append(f)
    lines = ['## Footage', '']
    if not files:
        return lines + ['(none)', '']
    for f in files:
        lines.append(f"- {f['credit_line']}")
    lines.append('')
    if any(f.get('licence', '').upper().startswith('CC BY-SA') for f in files):
        lines = [
            'At least one file below is CC BY-SA: publishing this edit means releasing it under '
            'the same licence, or dropping that file first.', ''
        ] + lines
    return lines


def build(music_index, sfx_index, footage_manifests, only_tracks=None, only_effects=None, only_footage=None):
    lines = [
        '# Credits', '',
        'Generated by scripts/credits.py. Nothing here is posted anywhere by this tool; it '
        'only writes the text to show if the edit is ever published.', '',
    ]
    lines += music_section(music_index, only_tracks)
    lines += sfx_section(sfx_index, only_effects)
    if footage_manifests:
        lines += footage_section(footage_manifests, only_footage)
    return '\n'.join(lines).rstrip() + '\n'


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--music', help='path to a music/index.json')
    p.add_argument('--sfx', help='path to an sfx/index.json')
    p.add_argument('--footage', nargs='*', default=[], help='one or more tests/<name>/sources.json footage manifests')
    p.add_argument('--tracks', help='comma-separated track paths/titles to include (default: all)')
    p.add_argument('--effects', help='comma-separated effect ids/names to include (default: all)')
    p.add_argument('--footage-files', help='comma-separated footage local_paths/titles to include (default: all)')
    p.add_argument('--out', required=True)
    a = p.parse_args()

    music_index = _load(a.music) or []
    sfx_index = _load(a.sfx) or {}
    footage_manifests = [_load(f) for f in a.footage]

    only_tracks = set(a.tracks.split(',')) if a.tracks else None
    only_effects = set(a.effects.split(',')) if a.effects else None
    only_footage = set(a.footage_files.split(',')) if a.footage_files else None

    text = build(music_index, sfx_index, footage_manifests, only_tracks, only_effects, only_footage)
    Path(a.out).write_text(text, encoding='utf-8')
    print(f'wrote {a.out}')


if __name__ == '__main__':
    main()
